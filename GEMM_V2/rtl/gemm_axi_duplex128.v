`timescale 1ns/1ps
// Independent read and write command channels on one AXI4 master interface.
// Each direction reserves up to two bursts; read and write transactions may
// progress concurrently. Errors and command completion are isolated by direction.
// Reset is synchronous to clk inside both command engines.
module gemm_axi_duplex128 #(
    parameter integer C_M_AXI_ID_WIDTH     = 1,
    parameter integer C_M_AXI_AWUSER_WIDTH = 0,
    parameter integer C_M_AXI_ARUSER_WIDTH = 0,
    parameter integer C_M_AXI_WUSER_WIDTH  = 0,
    parameter integer C_M_AXI_RUSER_WIDTH  = 0,
    parameter integer C_M_AXI_BUSER_WIDTH  = 0,
    parameter integer MAX_BURST = 256,
    parameter integer READ_ALWAYS_READY = 0,
    parameter integer STRIDED_WRITE = 0
)(
    input wire clk,input wire rst_n,
    input wire rd_cmd_valid,output wire rd_cmd_ready,
    input wire [31:0] rd_cmd_addr,input wire [31:0] rd_cmd_bytes,
    output wire rd_done,output wire rd_error,output wire rd_busy,
    output wire [127:0] rx_data,output wire rx_valid,input wire rx_ready,
    input wire wr_cmd_valid,output wire wr_cmd_ready,
    input wire [31:0] wr_cmd_addr,input wire [31:0] wr_cmd_bytes,
    input wire wr_cmd_strided,input wire [31:0] wr_cmd_stride,
    output wire wr_done,output wire wr_error,output wire wr_busy,
    input wire [127:0] tx_data,input wire tx_valid,output wire tx_ready,
	output wire [C_M_AXI_ID_WIDTH-1 : 0]        m_axi_awid,
	output wire [31 : 0]      m_axi_awaddr,
	output wire [7 : 0]                         m_axi_awlen,
	output wire [2 : 0]                         m_axi_awsize,
	output wire [1 : 0]                         m_axi_awburst,
	output wire                                 m_axi_awlock,
	output wire [3 : 0]                         m_axi_awcache,
	output wire [2 : 0]                         m_axi_awprot,
	output wire [3 : 0]                         m_axi_awqos,
	output wire [(C_M_AXI_AWUSER_WIDTH > 0 ? C_M_AXI_AWUSER_WIDTH : 1)-1 : 0]    m_axi_awuser,
	output wire                                 m_axi_awvalid,
	input  wire                                 m_axi_awready,
	output wire [128-1 : 0]      m_axi_wdata,
	output wire [128/8-1 : 0]    m_axi_wstrb,
	output wire                                 m_axi_wlast,
	output wire [(C_M_AXI_WUSER_WIDTH > 0 ? C_M_AXI_WUSER_WIDTH : 1)-1 : 0]     m_axi_wuser,
	output wire                                 m_axi_wvalid,
	input  wire                                 m_axi_wready,
	input  wire [C_M_AXI_ID_WIDTH-1 : 0]        m_axi_bid,
	input  wire [1 : 0]                         m_axi_bresp,
	input  wire [(C_M_AXI_BUSER_WIDTH > 0 ? C_M_AXI_BUSER_WIDTH : 1)-1 : 0]     m_axi_buser,
	input  wire                                 m_axi_bvalid,
	output wire                                 m_axi_bready,
	output wire [C_M_AXI_ID_WIDTH-1 : 0]        m_axi_arid,
	output wire [31 : 0]      m_axi_araddr,
	output wire [7 : 0]                         m_axi_arlen,
	output wire [2 : 0]                         m_axi_arsize,
	output wire [1 : 0]                         m_axi_arburst,
	output wire                                 m_axi_arlock,
	output wire [3 : 0]                         m_axi_arcache,
	output wire [2 : 0]                         m_axi_arprot,
	output wire [3 : 0]                         m_axi_arqos,
	output wire [(C_M_AXI_ARUSER_WIDTH > 0 ? C_M_AXI_ARUSER_WIDTH : 1)-1 : 0]    m_axi_aruser,
	output wire                                 m_axi_arvalid,
	input  wire                                 m_axi_arready,
	input  wire [C_M_AXI_ID_WIDTH-1 : 0]        m_axi_rid,
	input  wire [128-1 : 0]      m_axi_rdata,
	input  wire [1 : 0]                         m_axi_rresp,
	input  wire                                 m_axi_rlast,
	input  wire [(C_M_AXI_RUSER_WIDTH > 0 ? C_M_AXI_RUSER_WIDTH : 1)-1 : 0]     m_axi_ruser,
	input  wire                                 m_axi_rvalid,
	output wire                                 m_axi_rready
);
    gemm_axi_dma128 #(
        .C_M_AXI_ID_WIDTH(C_M_AXI_ID_WIDTH),
        .C_M_AXI_AWUSER_WIDTH(C_M_AXI_AWUSER_WIDTH),
        .C_M_AXI_ARUSER_WIDTH(C_M_AXI_ARUSER_WIDTH),
        .C_M_AXI_WUSER_WIDTH(C_M_AXI_WUSER_WIDTH),
        .C_M_AXI_RUSER_WIDTH(C_M_AXI_RUSER_WIDTH),
        .C_M_AXI_BUSER_WIDTH(C_M_AXI_BUSER_WIDTH),
        .MAX_BURST(MAX_BURST),.RX_ALWAYS_READY(READ_ALWAYS_READY)
    ) u_read (
        .clk(clk),.rst_n(rst_n),
        .cmd_valid(rd_cmd_valid),.cmd_ready(rd_cmd_ready),.cmd_write(1'b0),
        .cmd_addr(rd_cmd_addr),.cmd_bytes(rd_cmd_bytes),.cmd_strided(1'b0),.cmd_stride(32'd0),
        .done(rd_done),.error(rd_error),.busy(rd_busy),
        .rx_data(rx_data),.rx_valid(rx_valid),.rx_ready(rx_ready),
        .tx_data(128'b0),.tx_valid(1'b0),.tx_ready(),
        .m_axi_awid(),
        .m_axi_awaddr(),
        .m_axi_awlen(),
        .m_axi_awsize(),
        .m_axi_awburst(),
        .m_axi_awlock(),
        .m_axi_awcache(),
        .m_axi_awprot(),
        .m_axi_awqos(),
        .m_axi_awuser(),
        .m_axi_awvalid(),
        .m_axi_awready(1'b0),
        .m_axi_wdata(),
        .m_axi_wstrb(),
        .m_axi_wlast(),
        .m_axi_wuser(),
        .m_axi_wvalid(),
        .m_axi_wready(1'b0),
        .m_axi_bid({C_M_AXI_ID_WIDTH{1'b0}}),
        .m_axi_bresp(2'b00),
        .m_axi_buser({(C_M_AXI_BUSER_WIDTH>0?C_M_AXI_BUSER_WIDTH:1){1'b0}}),
        .m_axi_bvalid(1'b0),
        .m_axi_bready(),
        .m_axi_arid(m_axi_arid),
        .m_axi_araddr(m_axi_araddr),
        .m_axi_arlen(m_axi_arlen),
        .m_axi_arsize(m_axi_arsize),
        .m_axi_arburst(m_axi_arburst),
        .m_axi_arlock(m_axi_arlock),
        .m_axi_arcache(m_axi_arcache),
        .m_axi_arprot(m_axi_arprot),
        .m_axi_arqos(m_axi_arqos),
        .m_axi_aruser(m_axi_aruser),
        .m_axi_arvalid(m_axi_arvalid),
        .m_axi_arready(m_axi_arready),
        .m_axi_rid(m_axi_rid),
        .m_axi_rdata(m_axi_rdata),
        .m_axi_rresp(m_axi_rresp),
        .m_axi_rlast(m_axi_rlast),
        .m_axi_ruser(m_axi_ruser),
        .m_axi_rvalid(m_axi_rvalid),
        .m_axi_rready(m_axi_rready)
    );
    gemm_axi_dma128 #(
        .C_M_AXI_ID_WIDTH(C_M_AXI_ID_WIDTH),
        .C_M_AXI_AWUSER_WIDTH(C_M_AXI_AWUSER_WIDTH),
        .C_M_AXI_ARUSER_WIDTH(C_M_AXI_ARUSER_WIDTH),
        .C_M_AXI_WUSER_WIDTH(C_M_AXI_WUSER_WIDTH),
        .C_M_AXI_RUSER_WIDTH(C_M_AXI_RUSER_WIDTH),
        .C_M_AXI_BUSER_WIDTH(C_M_AXI_BUSER_WIDTH),
        .MAX_BURST(MAX_BURST),.STRIDED_WRITE(STRIDED_WRITE)
    ) u_write (
        .clk(clk),.rst_n(rst_n),
        .cmd_valid(wr_cmd_valid),.cmd_ready(wr_cmd_ready),.cmd_write(1'b1),
        .cmd_addr(wr_cmd_addr),.cmd_bytes(wr_cmd_bytes),.cmd_strided(wr_cmd_strided),.cmd_stride(wr_cmd_stride),
        .done(wr_done),.error(wr_error),.busy(wr_busy),
        .rx_data(),.rx_valid(),.rx_ready(1'b1),
        .tx_data(tx_data),.tx_valid(tx_valid),.tx_ready(tx_ready),
        .m_axi_awid(m_axi_awid),
        .m_axi_awaddr(m_axi_awaddr),
        .m_axi_awlen(m_axi_awlen),
        .m_axi_awsize(m_axi_awsize),
        .m_axi_awburst(m_axi_awburst),
        .m_axi_awlock(m_axi_awlock),
        .m_axi_awcache(m_axi_awcache),
        .m_axi_awprot(m_axi_awprot),
        .m_axi_awqos(m_axi_awqos),
        .m_axi_awuser(m_axi_awuser),
        .m_axi_awvalid(m_axi_awvalid),
        .m_axi_awready(m_axi_awready),
        .m_axi_wdata(m_axi_wdata),
        .m_axi_wstrb(m_axi_wstrb),
        .m_axi_wlast(m_axi_wlast),
        .m_axi_wuser(m_axi_wuser),
        .m_axi_wvalid(m_axi_wvalid),
        .m_axi_wready(m_axi_wready),
        .m_axi_bid(m_axi_bid),
        .m_axi_bresp(m_axi_bresp),
        .m_axi_buser(m_axi_buser),
        .m_axi_bvalid(m_axi_bvalid),
        .m_axi_bready(m_axi_bready),
        .m_axi_arid(),
        .m_axi_araddr(),
        .m_axi_arlen(),
        .m_axi_arsize(),
        .m_axi_arburst(),
        .m_axi_arlock(),
        .m_axi_arcache(),
        .m_axi_arprot(),
        .m_axi_arqos(),
        .m_axi_aruser(),
        .m_axi_arvalid(),
        .m_axi_arready(1'b0),
        .m_axi_rid({C_M_AXI_ID_WIDTH{1'b0}}),
        .m_axi_rdata(128'b0),
        .m_axi_rresp(2'b00),
        .m_axi_rlast(1'b0),
        .m_axi_ruser({(C_M_AXI_RUSER_WIDTH>0?C_M_AXI_RUSER_WIDTH:1){1'b0}}),
        .m_axi_rvalid(1'b0),
        .m_axi_rready()
    );
endmodule
